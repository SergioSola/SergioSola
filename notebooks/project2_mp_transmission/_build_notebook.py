cells.append(md([
    "## 2. Conceptual Framework\n",
    "\n",
    "### 2.1 The Monetary Policy Transmission Chain\n",
    "\n",
    "We decompose the monetary policy transmission mechanism through non-bank intermediaries into four\n",
    "sequential links:\n",
    "\n",
    "$$\n",
    "\\underbrace{\\Delta i^{\\text{policy}}}_{\\text{Link 1}}\n",
    "\\;\\xrightarrow{\\text{term structure}}\\;\n",
    "\\underbrace{\\Delta \\text{NBFI Balance Sheets}}_{\\text{Link 2}}\n",
    "\\;\\xrightarrow{\\text{leverage constraint}}\\;\n",
    "\\underbrace{\\Delta y^{\\text{long}}, \\Delta s^{\\text{credit}}}_{\\text{Link 3}}\n",
    "\\;\\xrightarrow{\\text{financial conditions}}\\;\n",
    "\\underbrace{\\Delta \\text{GDP}, \\Delta \\text{Credit}}_{\\text{Link 4}}\n",
    "$$\n",
    "\n",
    "**Link 1: Policy rate to short-term rates.** Standard interest rate channel. The policy rate $i_t^{\\text{policy}}$\n",
    "transmits to money market rates and the short end of the yield curve.\n",
    "\n",
    "**Link 2: Short rates to NBFI balance sheets (Leverage Constraint Channel).** This is the Adrian and Shin\n",
    "(2010, 2014) VaR-constraint mechanism. NBFI intermediaries that target a VaR constraint face:\n",
    "\n",
    "$$\n",
    "\\text{Leverage}_t \\leq \\frac{1}{z_{\\alpha} \\cdot \\sigma_t}\n",
    "$$\n",
    "\n",
    "where $z_{\\alpha}$ is the VaR confidence quantile and $\\sigma_t$ is the estimated portfolio volatility.\n",
    "When monetary tightening raises volatility, the VaR constraint forces deleveraging:\n",
    "\n",
    "$$\n",
    "\\Delta \\log(\\text{Leverage}_t) = \\beta \\cdot \\Delta \\log(\\text{Assets}_t) + \\varepsilon_t\n",
    "$$\n",
    "\n",
    "with $\\beta > 0$ indicating procyclical leverage. The key insight from Banerjee et al. is that $\\beta$\n",
    "varies substantially across NBFI types.\n",
    "\n",
    "**Link 3: NBFI balance sheet adjustment to long-term yields and credit spreads.** When leveraged NBFIs\n",
    "deleverage, their forced asset sales depress prices and widen credit spreads. The magnitude depends on:\n",
    "- Market depth (fire-sale externality)\n",
    "- Correlation of positions across intermediaries (herding)\n",
    "- Time-varying bank-NBFI co-movement (DCC-GARCH)\n",
    "\n",
    "**Link 4: Yields and spreads to the real economy.** Tighter financial conditions feed through to\n",
    "investment and consumption. The Growth-at-Risk framework (Adrian et al. 2019) shows this link is\n",
    "inherently nonlinear — loose financial conditions compress the left tail of future growth.\n",
    "\n",
    "### 2.2 Modeling Each Link\n",
    "\n",
    "| Link | Mechanism | Model | Module |\n",
    "|------|-----------|-------|--------|\n",
    "| 1-2 | VaR constraint, procyclical leverage | Adrian-Shin regressions, fire-sale simulation | `src/models/var_amplification` |\n",
    "| 2-3 | Time-varying co-movement | DCC-GARCH(1,1) | `src/models/dcc_garch` |\n",
    "| 3-4 (linear) | Financial conditions to growth | Standard VAR | `src/analysis/systemic_risk` |\n",
    "| 3-4 (nonlinear) | Tail transmission | Quantile VAR, quantile connectedness | `src/econometrics/quantile_var` |\n",
    "| Full chain | Location + scale effects | Location-scale GaR | `src/econometrics/location_scale` |\n",
    "| Network | Spillover topology | Diebold-Yilmaz GFEVD | `src/analysis/systemic_risk` |\n",
    "\n",
    "### 2.3 Key Hypotheses\n",
    "\n",
    "**H1 (Heterogeneous amplification):** Procyclicality $\\beta$ is highest for hedge funds and leveraged\n",
    "investment funds, moderate for bond mutual funds and MMFs, and lowest for pension funds and insurance.\n",
    "\n",
    "**H2 (Nonlinear tail transmission):** Quantile IRFs at $\\tau = 0.05$ show 2-3x stronger responses\n",
    "than at $\\tau = 0.50$, especially for the policy rate $\\to$ hedge fund returns link.\n",
    "\n",
    "**H3 (Variance amplification):** NBFI leverage increases the conditional variance (not just the\n",
    "conditional mean) of future growth outcomes, generating fatter left tails.\n",
    "\n",
    "**H4 (Network containment):** During the 2022-23 hiking cycle, within-OFI connectedness was high\n",
    "but OFI-to-real-economy connectedness remained low, explaining the resilience puzzle."
]))

